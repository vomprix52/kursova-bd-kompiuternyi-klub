def sql_block(text, name):
    """Вирізає блок коду між маркерами '-- @@ name' або CREATE ... name."""
    m = re.search(rf"-- @@ {name} \|[^\n]*\n(.*?)(?=\n-- @@ |\n-- =====|\Z)", text, re.S)
    return m.group(1).strip()


def routine(text, name):
    m = re.search(rf"(CREATE (?:PROCEDURE|FUNCTION|TRIGGER|EVENT) {name}\b.*?END\$\$)", text, re.S)
    return m.group(1).replace("$$", ";")


def view(text, name):
    m = re.search(rf"(CREATE OR REPLACE VIEW {name} AS.*?;)", text, re.S)
    return m.group(1)


